    async def get_session_report_manifest(
        self,
        session_id: str,
        layers: tuple[int, ...] = (1, 2, 3),
    ) -> List[Dict[str, Any]]:
        """Return the latest report metadata without loading report bodies.

        The manifest is the report portion of the session bundle's retrieval
        projection.  ``content`` is deliberately excluded so persisted
        spatial snapshots do not duplicate L1/L2/L3 report text.
        """
        async with get_async_session() as db:
            statement = (
                select(DimensionReport)
                .where(
                    DimensionReport.session_id == session_id,
                    DimensionReport.layer.in_(layers),
                )
                .order_by(
                    DimensionReport.layer,
                    DimensionReport.dimension_key,
                    DimensionReport.version.desc(),
                )
            )
            result = await db.execute(statement)
            reports = result.scalars().all()

            manifest: List[Dict[str, Any]] = []
            seen: set[tuple[int, str]] = set()
            for report in reports:
                key = (report.layer, report.dimension_key)
                if key in seen:
                    continue
                seen.add(key)
                manifest.append({
                    "layer": report.layer,
                    "dimension_key": report.dimension_key,
                    "report_id": report.report_id,
                    "version": report.version,
                    "summary": report.summary or "",
                    "instruction": report.instruction or "",
                    "knowledge_sources": report.knowledge_sources or [],
                    "generated_at": (
                        report.generated_at.isoformat()
                        if report.generated_at else None
                    ),
                })
            return manifest

    async def get_layer_summaries(
        self,
        session_id: str,
        layer: int,
    ) -> Dict[str, Dict[str, Any]]:
        """
        Get structured summaries for all dimensions in a layer.

        Returns Dict mapping dim_key -> parsed summary dict.
        Much lighter than get_layer_reports() for cross-layer dependency loading.
        """
        from app.data.ingestion.summary_parser import parse_summary
        async with get_async_session() as db:
            statement = (
                select(DimensionReport)
                .where(
                    DimensionReport.session_id == session_id,
                    DimensionReport.layer == layer,
                )
                .order_by(DimensionReport.dimension_key, DimensionReport.version.desc())
            )
            result = await db.execute(statement)
            reports = result.scalars().all()

            summaries = {}
            seen_dims = set()
            for r in reports:
                if r.dimension_key not in seen_dims:
                    summaries[r.dimension_key] = parse_summary(r.summary, r.dimension_key, layer)
                    seen_dims.add(r.dimension_key)

            return summaries

    async def delete_session_reports(self, session_id: str) -> int:
        """
        Delete all reports for a session

        Args:
            session_id: Session identifier

        Returns:
            Number of deleted reports
        """
        async with _report_write_lock():
            async with get_async_session() as db:
                statement = select(DimensionReport).where(
                    DimensionReport.session_id == session_id
                )
                result = await db.execute(statement)
                reports = result.scalars().all()
                count = len(reports)

                for r in reports:
                    await db.delete(r)

                await db.commit()

                logger.info(f"[ReportStore] Deleted {count} reports for session {session_id}")
                return count


