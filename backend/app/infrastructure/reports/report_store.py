class ReportStore:
    """
    Report Storage and Version Management

    Database-backed storage using SQLModel.
    Replaces file-based storage for better query efficiency and consistency.
    """

    _instance: Optional["ReportStore"] = None

    def __init__(self):
        """Initialize report store"""
        logger.info("[ReportStore] Initialized with database backend")

    @classmethod
    def get_instance(cls) -> "ReportStore":
        """Get singleton instance"""
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    async def save(
        self,
        session_id: str,
        dim_key: str,
        version: int,
        content: str,
        metadata: Optional[Dict[str, Any]] = None,
        layer: int = 1,
        knowledge_sources: Optional[List[Dict[str, Any]]] = None,
        gis_data: Optional[List[Dict[str, Any]]] = None,
    ) -> str:
        """
        Save report and return report_id

        Args:
            session_id: Session identifier
            dim_key: Dimension key (e.g., "location", "land_use")
            version: Version number (1-based)
            content: Full report content
            metadata: Optional metadata (revision_reason, etc.)
            layer: Layer number (1/2/3)
            knowledge_sources: RAG knowledge sources
            gis_data: GIS tool results

        Returns:
            report_id: UUID for retrieving the report
        """
        report_id = str(uuid.uuid4())
        display_content = content
        summary = (metadata or {}).get("summary", '{"summary_status":"pending"}')

        db_report = DimensionReport(
            session_id=session_id,
            dimension_key=dim_key,
            layer=layer,
            version=version,
            report_id=report_id,
            content=display_content,
            instruction=(metadata or {}).get("instruction"),
            summary=summary,
            revision_trigger=metadata.get("revision_reason") if metadata else None,
            knowledge_sources=knowledge_sources,
            gis_data=gis_data,
            generated_at=datetime.now(),
        )

        async with _report_write_lock():
            async with get_async_session() as db:
                db.add(db_report)
                await db.commit()
                await db.refresh(db_report)

        logger.info(f"[ReportStore] Saved: {session_id}/{dim_key}/v{version} (id={report_id[:8]}...)")
        if _summary_needs_enrichment(summary):
            self.schedule_summary(session_id, dim_key, layer, version, report_id)
        return report_id

    async def bulk_save(self, reports: List[Dict[str, Any]]) -> List[str]:
        """
        批量保存报告（单事务，upsert 语义）

        性能优化：将多个报告在一次事务中写入数据库，
        减少 N transactions -> 1 transaction。

        使用 INSERT OR REPLACE 处理重复 report_id，避免 UNIQUE constraint 失败。

        Args:
            reports: 报告数据列表，每个元素包含：
                - session_id: Session identifier
                - dimension_key: Dimension key
                - layer: Layer number
                - version: Version number
                - report_id: UUID
                - content: Full report content
                - summary: Summary text
                - knowledge_sources: Optional RAG sources
                - gis_data: Optional GIS data
                - generated_at: Timestamp

        Returns:
            List of report_ids
        """
        if not reports:
            return []

        async with _report_write_lock():
            async with get_async_session() as db:
                for report_data in reports:
                    # Check if report_id already exists
                    existing = await db.execute(
                        select(DimensionReport).where(
                            DimensionReport.report_id == report_data["report_id"]
                        )
                    )
                    existing_report = existing.scalar_one_or_none()

                    # ``report_id`` is the replay idempotency key for current
                    # L3 writes.  Also match the natural identity so a
                    # checkpoint created before that key was introduced does
                    # not leave a second row for the same logical version.
                    if existing_report is None:
                        natural_key = await db.execute(
                            select(DimensionReport)
                            .where(
                                DimensionReport.session_id == report_data["session_id"],
                                DimensionReport.dimension_key == report_data["dimension_key"],
                                DimensionReport.version == report_data["version"],
                            )
                            .order_by(DimensionReport.id)
                            .limit(1)
                        )
                        existing_report = natural_key.scalar_one_or_none()

                    if existing_report:
                        # Update existing report
                        existing_report.session_id = report_data["session_id"]
                        existing_report.dimension_key = report_data["dimension_key"]
                        existing_report.layer = report_data["layer"]
                        existing_report.version = report_data["version"]
                        existing_report.report_id = report_data["report_id"]
                        existing_report.content = report_data["content"]
                        existing_report.instruction = report_data.get("instruction")
                        existing_report.summary = report_data.get("summary", "")
                        existing_report.revision_trigger = report_data.get("revision_trigger")
                        existing_report.knowledge_sources = report_data.get("knowledge_sources")
                        existing_report.gis_data = report_data.get("gis_data")
                        existing_report.generated_at = report_data.get("generated_at", datetime.now())
                    else:
                        # Insert new report
                        db_report = DimensionReport(
                            session_id=report_data["session_id"],
                            dimension_key=report_data["dimension_key"],
                            layer=report_data["layer"],
                            version=report_data["version"],
                            report_id=report_data["report_id"],
                            content=report_data["content"],
                            instruction=report_data.get("instruction"),
                            summary=report_data.get("summary", ""),
                            revision_trigger=report_data.get("revision_trigger"),
                            knowledge_sources=report_data.get("knowledge_sources"),
                            gis_data=report_data.get("gis_data"),
                            generated_at=report_data.get("generated_at", datetime.now()),
                        )
                        db.add(db_report)
                await db.commit()

        report_ids = [r["report_id"] for r in reports]
        logger.info(f"[ReportStore] Bulk saved {len(reports)} reports: {[r['dimension_key'] for r in reports]}")
        for report_data in reports:
            if _summary_needs_enrichment(report_data.get("summary", "")):
                self.schedule_summary(
                    report_data["session_id"],
                    report_data["dimension_key"],
                    report_data["layer"],
                    report_data["version"],
                    report_data["report_id"],
                )
        return report_ids

    async def update_summary(self, session_id: str, dim_key: str, version: int, summary: str, report_id: str) -> bool:
        """Update the summary of an existing report (async background enrichment).

        Returns True if updated, False if the report row was not found.
        """
        async with _report_write_lock():
            async with get_async_session() as db:
                result = await db.execute(
                    update(DimensionReport)
                    .where(
                        DimensionReport.session_id == session_id,
                        DimensionReport.dimension_key == dim_key,
                        DimensionReport.version == version,
                        DimensionReport.report_id == report_id,
                    )
                    .values(summary=summary)
                )
                if int(getattr(result, "rowcount", 0) or 0) != 1:
                    return False
                await db.commit()
                return True

    async def _get_summary_source(self, session_id: str, dim_key: str, version: int, report_id: str) -> tuple[str, Any] | None:
        """Load the complete source only inside the async summary worker."""
        async with get_async_session() as db:
            result = await db.execute(
                select(DimensionReport.content, DimensionReport.instruction).where(
                    DimensionReport.session_id == session_id,
                    DimensionReport.dimension_key == dim_key,
                    DimensionReport.version == version,
                    DimensionReport.report_id == report_id,
                )
            )
            row = result.one_or_none()
            if row is None:
                return None
            return str(row[0] or ""), row[1]

    def schedule_summary(self, session_id: str, dim_key: str, layer: int, version: int, report_id: str):
        from app.bootstrap.composition import CompositionRoot
        from app.infrastructure.tasks.task_supervisor import build_summary_task_key

        async def run():
            from app.infrastructure.evidence_runtime.dimension_runtime import generate_summary
            source = await self._get_summary_source(session_id, dim_key, version, report_id)
            if source is None:
                return
            content, instruction = source
            # The summary worker owns the only read of the complete report
            # source.  Keep the typed instruction beside the full report body
            # instead of replacing the body with an instruction-only view;
            # the display summary must be able to see every report section.
            source_artifact = {
                "report_body": content,
                "typed_instruction": instruction,
            }
            summary = await generate_summary(
                dim_key,
                layer,
                content,
                source_artifact=source_artifact,
            )
            await self.update_summary(session_id, dim_key, version, summary, report_id=report_id)

        try:
            supervisor = CompositionRoot.get_task_supervisor()
        except Exception as exc:
            logger.warning("[ReportStore] Summary supervisor unavailable: %s", type(exc).__name__)
            return None
        coroutine = run()
        try:
            return supervisor.create_task(
                build_summary_task_key(session_id, layer, dim_key, version, report_id),
                coroutine,
            )
        except Exception as exc:
            coroutine.close()
            logger.warning("[ReportStore] Summary task not scheduled: %s", type(exc).__name__)
            return None

    async def get_latest_dependency_records(self, session_id: str, dependency_keys: List[str]) -> Dict[str, Dict[str, Any]]:
        keys = [str(key).strip() for key in dependency_keys if str(key).strip()]
        if not keys:
            return {}
        async with get_async_session() as db:
            result = await db.execute(
                select(
                    DimensionReport.dimension_key, DimensionReport.layer,
                    DimensionReport.version, DimensionReport.report_id,
                    DimensionReport.summary, DimensionReport.instruction,
                ).where(
                    DimensionReport.session_id == session_id,
                    DimensionReport.dimension_key.in_(keys),
                ).order_by(DimensionReport.dimension_key, DimensionReport.version.desc())
            )
            records: Dict[str, Dict[str, Any]] = {}
            for row in result.all():
                if row.dimension_key not in records:
                    records[row.dimension_key] = dict(row._mapping)
            return records

    @staticmethod
    def parse_summary(summary: str) -> Dict[str, Any]:
        """Parse summary field, handling both JSON and plain text formats."""
        if not summary:
            return {"summary": ""}
        if summary.strip().startswith('{'):
            try:
                return json.loads(summary)
            except json.JSONDecodeError:
                pass
        return {"summary": summary}
